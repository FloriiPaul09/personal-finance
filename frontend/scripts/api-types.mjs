// Generates the API types (src/app/core/api/schema.ts) from the OpenAPI document of the API.
//
//   pnpm api:types                       # from the API running in Development (http://localhost:5080)
//   pnpm api:types --url <document url>  # from another address
//   pnpm api:types --file <path>         # from a saved document, e.g. the committed snapshot
//
// The document is saved as src/app/core/api/openapi.json (the snapshot the types come from),
// then adjusted (see `adjust`) and turned into types with openapi-typescript.
// docs/frontend/app-structure.md#api-types
import { readFile, writeFile } from 'node:fs/promises';
import { parseArgs } from 'node:util';
import openapiTS, { astToString } from 'openapi-typescript';
import * as prettier from 'prettier';

const SNAPSHOT = new URL('../src/app/core/api/openapi.json', import.meta.url);
const OUTPUT = new URL('../src/app/core/api/schema.ts', import.meta.url);

const { values } = parseArgs({
  options: {
    url: { type: 'string', default: 'http://localhost:5080/openapi/v1.json' },
    file: { type: 'string' },
  },
});

const document = values.file
  ? JSON.parse(await readFile(values.file, 'utf8'))
  : await download(values.url);

if (!values.file) {
  await writeFile(SNAPSHOT, await format(JSON.stringify(document), SNAPSHOT));
}

const ast = await openapiTS(adjust(structuredClone(document)));
const header = [
  '// Generated by `pnpm api:types` from src/app/core/api/openapi.json. Do not edit by hand.',
  '// Import the aliases in ./models.ts instead of these raw types.',
  '',
].join('\n');
await writeFile(OUTPUT, await format(header + astToString(ast), OUTPUT));
console.log(`Wrote ${OUTPUT.pathname}`);

async function format(text, file) {
  const options = await prettier.resolveConfig(file);
  return prettier.format(text, { ...options, filepath: file.pathname });
}

async function download(url) {
  let response;
  try {
    response = await fetch(url);
  } catch (error) {
    throw new Error(
      `Cannot reach ${url}. Start the API in Development (dotnet watch --project backend/src/Api), ` +
        'or pass --file with a saved document.',
      { cause: error },
    );
  }
  if (!response.ok) {
    throw new Error(`${url} answered ${response.status}: is the API running in Development?`);
  }
  return response.json();
}

/**
 * Adjusts the document where it describes the wire format more loosely than the API behaves.
 * Each rule can go once the backend describes the value precisely (handed off to [Backend]).
 *
 * 1. Numbers: ASP.NET Core's web JSON defaults also *read* numbers written as strings, so every
 *    number is described as `number | string` (with a pattern). The API always *writes* JSON
 *    numbers and the app always sends numbers: keep `number` / `integer` only.
 * 2. Months (`YearMonth`): described as an empty schema; on the wire they are "yyyy-MM" strings.
 */
export function adjust(node) {
  if (Array.isArray(node)) {
    node.forEach(adjust);
    return node;
  }
  if (node === null || typeof node !== 'object') {
    return node;
  }
  if (Array.isArray(node.type) && node.type.includes('string')) {
    const numeric = node.type.filter((t) => t === 'number' || t === 'integer');
    if (numeric.length > 0) {
      const rest = node.type.filter((t) => t !== 'string');
      node.type = rest.length === 1 ? rest[0] : rest;
      delete node.pattern;
    }
  }
  const yearMonth = node.components?.schemas?.YearMonth;
  if (yearMonth && Object.keys(yearMonth).length === 0) {
    node.components.schemas.YearMonth = {
      type: 'string',
      pattern: '^\\d{4}-\\d{2}$',
      description: 'A month, written yyyy-MM.',
    };
  }
  Object.values(node).forEach(adjust);
  return node;
}
