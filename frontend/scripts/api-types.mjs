// Generates the API types (src/app/core/api/schema.ts) from the OpenAPI document of the API.
//
//   pnpm api:types                       # builds the API and reads the document it writes (no API running)
//   pnpm api:types --file <path>         # from a saved document, e.g. the one a CI build exported
//   pnpm api:types --url <document url>  # from a running API, e.g. http://localhost:5080/openapi/v1.json
//
// The document is saved, formatted, as src/app/core/api/openapi.json (the snapshot the types come from), then turned
// into types with openapi-typescript as it is: the backend describes numbers, months, versions and errors precisely
// (ADR-0029), so nothing is adjusted here. docs/frontend/app-structure.md#api-types
import { execFileSync } from 'node:child_process';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { parseArgs } from 'node:util';
import openapiTS, { astToString } from 'openapi-typescript';
import * as prettier from 'prettier';

const SNAPSHOT = new URL('../src/app/core/api/openapi.json', import.meta.url);
const OUTPUT = new URL('../src/app/core/api/schema.ts', import.meta.url);
const API_PROJECT = new URL('../../backend/src/Api', import.meta.url);
const BUILT_DOCUMENT = new URL('../../backend/artifacts/openapi/openapi.json', import.meta.url);

const { values } = parseArgs({
  options: {
    url: { type: 'string' },
    file: { type: 'string' },
  },
});

const document = values.url
  ? await download(values.url)
  : JSON.parse(await readFile(values.file ?? buildDocument(), 'utf8'));

await writeFile(SNAPSHOT, await format(JSON.stringify(document), SNAPSHOT));

const ast = await openapiTS(document);
const header = [
  '// Generated by `pnpm api:types` from src/app/core/api/openapi.json. Do not edit by hand.',
  '// Import the aliases in ./models.ts instead of these raw types.',
  '',
].join('\n');
await writeFile(OUTPUT, await format(header + astToString(ast), OUTPUT));
console.log(`Wrote ${fileURLToPath(SNAPSHOT)} and ${fileURLToPath(OUTPUT)}`);

/** Builds the API with the document export turned on (docs/backend/api-endpoints.md#openapi). */
function buildDocument() {
  const project = fileURLToPath(API_PROJECT);
  console.log(`Building ${project} to export the OpenAPI document…`);
  execFileSync('dotnet', ['build', project, '-p:OpenApiGenerateDocuments=true', '--nologo', '-v', 'q'], {
    stdio: 'inherit',
  });
  return fileURLToPath(BUILT_DOCUMENT);
}

async function format(text, file) {
  const options = await prettier.resolveConfig(file);
  return prettier.format(text, { ...options, filepath: fileURLToPath(file) });
}

async function download(url) {
  let response;
  try {
    response = await fetch(url);
  } catch (error) {
    throw new Error(
      `Cannot reach ${url}. Start the API in Development (dotnet watch --project backend/src/Api), ` +
        'or run pnpm api:types without --url to build the document.',
      { cause: error },
    );
  }
  if (!response.ok) {
    throw new Error(`${url} answered ${response.status}: is the API running in Development?`);
  }
  return response.json();
}
