using System.Collections.Concurrent;
using Npgsql;
using Testcontainers.PostgreSql;
using Xunit;

namespace PersonalFinance.Testing;

/// <summary>
/// One PostgreSQL container per test run, with a template database prepared once and cloned for every
/// test class (ADR-0011, docs/database/testing.md).
/// </summary>
/// <remarks>
/// Each integration test project registers a concrete subclass as assembly fixture:
/// <c>[assembly: AssemblyFixture(typeof(DatabaseServer))]</c>. xUnit fixtures cannot depend on each other,
/// so the per-class databases are created and cached here, by test class.
/// </remarks>
public abstract class PostgresServerFixture : IAsyncLifetime
{
    /// <summary>Database prepared once (migrations) and used as template for every test database.</summary>
    public const string TemplateDatabaseName = "pf_template";

    private const string TestDatabasePrefix = "pf_test_";

    private readonly PostgreSqlContainer _container = new PostgreSqlBuilder(PostgresImage.Name).Build();
    private readonly ConcurrentDictionary<Type, Lazy<Task<TestDatabase>>> _classDatabases = new();
    private readonly SemaphoreSlim _cloneLock = new(1, 1);

    public async ValueTask InitializeAsync()
    {
        await _container.StartAsync();
        await ExecuteAsync(AdminConnectionString, $"CREATE DATABASE {Quote(TemplateDatabaseName)}", CancellationToken.None);
        await InitializeTemplateAsync(ConnectionStringFor(TemplateDatabaseName));

        // PostgreSQL refuses to copy a database while someone is connected to it.
        NpgsqlConnection.ClearAllPools();
    }

    /// <summary>The database shared by all the tests of <paramref name="testClass"/>, created on first use.</summary>
    public Task<TestDatabase> DatabaseForClassAsync(Type testClass) =>
        _classDatabases.GetOrAdd(testClass, _ => new Lazy<Task<TestDatabase>>(() => CreateDatabaseAsync())).Value;

    /// <summary>A new database cloned from the template, for tests that need more than one.</summary>
    public async Task<TestDatabase> CreateDatabaseAsync(CancellationToken cancellationToken = default)
    {
        var name = TestDatabasePrefix + Guid.NewGuid().ToString("N");

        await _cloneLock.WaitAsync(cancellationToken);
        try
        {
            await ExecuteAsync(
                AdminConnectionString,
                $"CREATE DATABASE {Quote(name)} TEMPLATE {Quote(TemplateDatabaseName)}",
                cancellationToken);
        }
        finally
        {
            _cloneLock.Release();
        }

        return new TestDatabase(name, ConnectionStringFor(name));
    }

    public async ValueTask DisposeAsync()
    {
        NpgsqlConnection.ClearAllPools();
        await _container.DisposeAsync();
        _cloneLock.Dispose();
        GC.SuppressFinalize(this);
    }

    /// <summary>
    /// Prepares the template database once per run. Overridden by test projects to apply the migrations;
    /// every connection opened here must be closed before returning.
    /// </summary>
    protected virtual Task InitializeTemplateAsync(string connectionString) => Task.CompletedTask;

    private string AdminConnectionString => _container.GetConnectionString();

    private string ConnectionStringFor(string database) =>
        new NpgsqlConnectionStringBuilder(AdminConnectionString) { Database = database }.ConnectionString;

    // Names are generated by this class, never taken from input.
    private static string Quote(string identifier) => $"\"{identifier}\"";

    private static async Task ExecuteAsync(string connectionString, string sql, CancellationToken cancellationToken)
    {
        await using var connection = new NpgsqlConnection(connectionString);
        await connection.OpenAsync(cancellationToken);
        await using var command = new NpgsqlCommand(sql, connection);
        await command.ExecuteNonQueryAsync(cancellationToken);
    }
}
