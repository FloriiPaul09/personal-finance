using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Metadata.Builders;
using PersonalFinance.Domain.Common;
using PersonalFinance.Infrastructure.Identity;

namespace PersonalFinance.Infrastructure.Persistence.Configurations;

/// <summary>Mapping shared by every entity deriving from <see cref="OwnedEntity"/> (docs/database/conventions.md).</summary>
internal static class OwnedEntityMapping
{
    /// <summary>Name of the shadow property mapped to PostgreSQL's <c>xmin</c> system column.</summary>
    public const string VersionProperty = RowVersion.PropertyName;

    public static void MapOwnedEntity<TEntity>(this EntityTypeBuilder<TEntity> builder)
        where TEntity : OwnedEntity
    {
        builder.HasKey(entity => entity.Id);

        // Generated by the domain at creation (UUIDv7).
        builder.Property(entity => entity.Id).ValueGeneratedNever();

        // Target of the composite foreign keys that keep references inside one user.
        builder.HasAlternateKey(entity => new { entity.UserId, entity.Id });

        builder.HasOne<ApplicationUser>()
            .WithMany()
            .HasForeignKey(entity => entity.UserId)
            .OnDelete(DeleteBehavior.Cascade);

        // Optimistic concurrency on the row version PostgreSQL keeps anyway: no extra column.
        builder.Property<uint>(VersionProperty)
            .HasColumnName("xmin")
            .HasColumnType("xid")
            .ValueGeneratedOnAddOrUpdate()
            .IsConcurrencyToken();
    }
}
